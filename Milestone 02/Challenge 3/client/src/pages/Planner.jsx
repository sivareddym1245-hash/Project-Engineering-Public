import { useEffect, useState } from 'react';
import { ArrowRight, Bot, Sparkles } from 'lucide-react';
import { fetchTasks, generateTaskPlan } from '../services/api';

const Planner = () => {
  const [tasks, setTasks] = useState([]);
  const [tasksLoading, setTasksLoading] = useState(true);
  const [tasksError, setTasksError] = useState('');
  const [goal, setGoal] = useState('');
  const [plan, setPlan] = useState('');
  const [model, setModel] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => {
    let active = true;
    fetchTasks()
      .then((data) => {
        if (active) {
          setTasks(data.filter((task) => !task.completed));
          setTasksError('');
        }
      })
      .catch((err) => {
        if (active) {
          setTasksError(err.message);
        }
      })
      .finally(() => {
        if (active) setTasksLoading(false);
      });

    return () => {
      active = false;
    };
  }, []);

  const handleSubmit = async (event) => {
    event.preventDefault();
    const trimmedGoal = goal.trim();
    if (trimmedGoal.length < 3 || trimmedGoal.length > 500) {
      setError('Describe your goal in 3 to 500 characters.');
      return;
    }

    setIsSubmitting(true);
    setError('');
    setPlan('');
    try {
      const result = await generateTaskPlan(trimmedGoal);
      setPlan(result.plan);
      setModel(result.model);
    } catch (err) {
      setError(err.message);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <section className="planner-page animate-fade">
      <header className="welcome-section">
        <p className="planner-eyebrow"><Sparkles size={16} /> AI TASK PLANNER</p>
        <h1>Find your next step.</h1>
        <p>Share what you want to get done. TaskNest will make a practical plan from your open tasks.</p>
      </header>

      <div className="planner-grid">
        <form className="form-card planner-form" onSubmit={handleSubmit}>
          <label htmlFor="planner-goal">What would you like to make progress on?</label>
          <textarea
            id="planner-goal"
            className="styled-input planner-textarea"
            value={goal}
            onChange={(event) => setGoal(event.target.value)}
            placeholder="For example: help me prepare for my project review this week"
            maxLength={500}
            minLength={3}
            required
          />
          <p className="planner-hint">
            {tasksLoading
              ? 'Loading your open tasks…'
              : tasksError
                ? `Your task list could not be loaded: ${tasksError}`
                : `${tasks.length} open task${tasks.length === 1 ? '' : 's'} will be considered, with important tasks prioritized.`}
          </p>
          <button type="submit" className="primary-button" disabled={isSubmitting || tasksLoading}>
            <Sparkles size={19} />
            <span>{isSubmitting ? 'Building your plan…' : 'Build my plan'}</span>
            {!isSubmitting && <ArrowRight size={18} />}
          </button>
          <p className="planner-privacy">Your plan is generated by the backend and does not change or complete tasks.</p>
        </form>

        <aside className="planner-context" aria-label="Planner context">
          <div className="planner-icon"><Bot size={27} /></div>
          <h2>Grounded in your task list</h2>
          <p>The planner uses your goal and up to 30 open TaskNest tasks. It can suggest what to do next, but you stay in control of your task list.</p>
          <ul>
            <li>Important tasks are considered first.</li>
            <li>Suggestions are not saved automatically.</li>
            <li>Never share passwords or sensitive information.</li>
          </ul>
        </aside>
      </div>

      {error && <p className="form-error planner-message" role="alert">{error}</p>}

      {plan && (
        <section className="planner-result" aria-live="polite" aria-labelledby="planner-result-title">
          <div className="planner-result-heading">
            <div className="planner-icon"><Sparkles size={23} /></div>
            <div>
              <p className="planner-eyebrow">YOUR NEXT STEPS</p>
              <h2 id="planner-result-title">A plan for your goal</h2>
            </div>
          </div>
          <p className="planner-plan-text">{plan}</p>
          <p className="planner-model">Generated with {model}. Review suggestions before acting on them.</p>
        </section>
      )}
    </section>
  );
};

export default Planner;
